    public EditUserDialog(java.awt.Frame parent, boolean modal, DataStore ds, String userId) {
        super(parent, modal);

        
       for (int i = 0; i < DataStore.userCount; i++) {
            if (DataStore.users[i][0].equals(userId)) {
                this.userIndex = i;
                break;
            }
        }
       
       for (int i = 0; i < DataStore.patientCount; i++) {
            if (DataStore.patients[i][6].equals(userId)) {
                this.patientIndex = i;
                break;
            }
        }
       
       
        initComponents();
        loadDoctors();
        loadData();
    }
    private void loadDoctors(){
        DefaultComboBoxModel<String> model = new DefaultComboBoxModel<>();
        for (int i = 0; i < DataStore.userCount; i++) {
            if (DataStore.users[i][3].equalsIgnoreCase("doctor")) {
                // Format: "u001 - Dr. Name"
                model.addElement(DataStore.users[i][0] + " - " + DataStore.users[i][4]);
            }
        }
        cmbAssignedDoctor.setModel(model);
    }
    private void loadData() {
       if (userIndex == -1) return;

        String[] user = DataStore.users[userIndex];
        txtUserId.setText(user[0]);
        txtUsername.setText(user[1]);
        txtRole.setText(user[3]);
        txtFullName.setText(user[4]);

        // Only enable doctor assignment if the user is a Patient
        if (user[3].equalsIgnoreCase("patient") && patientIndex != -1) {
            cmbAssignedDoctor.setEnabled(true);
            String currentDocId = DataStore.patients[patientIndex][7];
            
            // Auto-select the current doctor in the combo box
            for (int i = 0; i < cmbAssignedDoctor.getItemCount(); i++) {
                if (cmbAssignedDoctor.getItemAt(i).startsWith(currentDocId)) {
                    cmbAssignedDoctor.setSelectedIndex(i);
                    break;
                }
            }
        } else {
            cmbAssignedDoctor.setEnabled(false);
        }
        
    }

