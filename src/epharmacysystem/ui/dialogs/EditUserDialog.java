    private void btnSaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSaveActionPerformed
    if (txtFullName.getText().trim().isEmpty() || txtUsername.getText().trim().isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Fields cannot be empty!");
            return;
        }

        // 1. Update the Main Users Array
        DataStore.users[userIndex][1] = txtUsername.getText().trim();
        DataStore.users[userIndex][4] = txtFullName.getText().trim();

        // 2. Update Patient specific data if applicable
        if (patientIndex != -1) {
            // Update name in patient record to stay in sync
            DataStore.patients[patientIndex][1] = txtFullName.getText().trim();
            
            // Update assigned doctor ID
            if (cmbAssignedDoctor.getSelectedItem() != null) {
                String docSelection = cmbAssignedDoctor.getSelectedItem().toString();
                String docId = docSelection.split(" - ")[0];
                DataStore.patients[patientIndex][7] = docId;
            }
        }

        javax.swing.JOptionPane.showMessageDialog(this, "User updated successfully!");
        this.dispose();
    }//GEN-LAST:event_btnSaveActionPerformed

