    private void btnSaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSaveActionPerformed
        if (txtFullName.getText().trim().isEmpty()
            || txtUsername.getText().trim().isEmpty()
            || txtPassword.getText().trim().isEmpty()
            || cmbRole.getSelectedItem() == null) {

        javax.swing.JOptionPane.showMessageDialog(this, "Please fill all fields!");
        return;
    }
        String selectedRole = cmbRole.getSelectedItem().toString().toLowerCase();
    if (selectedRole.equals(DataStore.ROLE_PATIENT) && 
       (cmbAssignedDoctor.getSelectedItem() == null || cmbAssignedDoctor.getSelectedIndex() == -1)) {
        
        javax.swing.JOptionPane.showMessageDialog(this, "Please assign a doctor for the new patient!");
        return;
    }
       if (DataStore.userCount >= 100) {
        javax.swing.JOptionPane.showMessageDialog(this, "User limit reached (100 users max)!");
        return;
    }

          String userId = String.format("u%03d", DataStore.userIdCounter);
      

       DataStore.users[DataStore.userCount] = new String[]{
        userId,
        txtUsername.getText().trim(),
        txtPassword.getText(),
        selectedRole,
        txtFullName.getText().trim()
    };

  if (selectedRole.equals(DataStore.ROLE_PATIENT)) {
        // Generate Patient ID (e.g., P003)
        String patientId = String.format("P%03d", DataStore.patientIdCounter);
        
        // Extract Doctor ID from combo box (assumes format "u001 - Dr. Name")
        String selectedDocEntry = cmbAssignedDoctor.getSelectedItem().toString();
        String assignedDoctorId = selectedDocEntry.split(" - ")[0];

        // Structure: {ID, Name, Age, Gender, Ward, History, UserID, DoctorID}
        DataStore.patients[DataStore.patientCount] = new String[]{
            patientId,
            txtFullName.getText().trim(),
            "0",                // Default Age (Admin can edit later)
            "Not Set",          // Default Gender
            "Unassigned",       // Default Ward
            "New Account",      // Default History
            userId,             // The Login ID we just made (uXXX)
            assignedDoctorId    // The Doctor ID this patient "belongs" to
        };

        DataStore.patientCount++;
        DataStore.patientIdCounter++;
    }

    // 6. Finalize User Creation
    DataStore.userCount++;
    DataStore.userIdCounter++;

        // 4. Success message
       javax.swing.JOptionPane.showMessageDialog(this, 
        "User " + txtFullName.getText() + " (" + userId + ") added successfully!");
       
        this.dispose();

    }//GEN-LAST:event_btnSaveActionPerformed

