    private void btnLoginActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnLoginActionPerformed
        // TODO add your handling code here:
        String username = txtUsername.getText();
        String password = new String(txtPassword.getPassword());

        boolean found = false;

        for (int i = 0; i < DataStore.userCount; i++){
            if (DataStore.users[i] == null) continue;
            
            String storedUsername = DataStore.users[i][1];
            String storedPassword = DataStore.users[i][2];
            String role = DataStore.users[i][3];
            String name = DataStore.users[i][4];
            String id = DataStore.users[i][0];
            if (username.equals(storedUsername) && password.equals(storedPassword))
            {
                found  = true;
                
                 DataStore.currentUserName = name;
                 DataStore.currentRole = role;
                 DataStore.currentUserId = id;
                javax.swing.JOptionPane.showMessageDialog(this, "Welcome " + name + " ("+ role + ")");
                switch (role) {
                    case DataStore.ROLE_DOCTOR:
                        new DoctorFrame().setVisible(true);
                        break;
                    case DataStore.ROLE_PATIENT:
                        new PatientFrame().setVisible(true);
                        break;
                    case DataStore.ROLE_PHARMACIST:
                        new PharmacistFrame().setVisible(true);
                        break;
                    case DataStore.ROLE_ADMIN:
                        new AdminFrame().setVisible(true);
                        break;    
                    default:
                        break;
                }
                this.dispose();
                break;
            }
        }
        if (!found) {
            javax.swing.JOptionPane.showMessageDialog(this,
                "Invalid username or password",
                "Login Failed",
                javax.swing.JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnLoginActionPerformed
  

